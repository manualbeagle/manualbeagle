"""docs/brands.md: one row per adapter, from the adapters' own YAML and an offline run of their test cases.

`manualbeagle adapters scoreboard --write docs/brands.md` regenerates it. Status is always a glyph plus a word,
so it reads without colour.

The nightly live run (`.github/workflows/live-adapters.yml`) adds two things from the results that
`manualbeagle adapters test --live --json FILE` writes: a scoreboard with a *Live* column
(`scoreboard --live FILE`), and `breakage()`, the Markdown report of every case that failed against the real
site, which becomes the "Live adapters" issue.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from datetime import date
from pathlib import Path

from .adapters import Registry
from .testing import BROKEN, GLYPHS, run_case

STATUS = {
    "works": "✓ works",
    "partial": "▲ partial",
    "link": "▲ link",
    "blocked": "✗ blocked",
    "untested": "? untested",
}

HEADER = """# Brands

Generated by `manualbeagle adapters scoreboard --write docs/brands.md` on {today}. Don't edit by hand.

**Status:** ✓ works = the adapter searches the maker's site and finds the documents itself. ▲ partial = it finds
some models, not all. ▲ link = no searching adapter yet: Manual Beagle knows the maker's domains (so web search
ranks the maker's own PDF first) and offers the maker's support page for a person to open. ✗ blocked = the maker's
site refuses automated requests (a bot wall or a login), which Manual Beagle never gets around, so it falls back
to web search.

**Tests:** each model is a test case in the adapter's YAML, replayed offline from recorded responses in CI and run
against the live site every night. ✓ passed, ✗ failed, – skipped (the reason is in the YAML).{live_note}

## How to help with a ▲ or ✗ brand

Start with [CONTRIBUTING.md](../CONTRIBUTING.md) ("Add a brand in 15 minutes") and the adapter reference,
[adapters.md](adapters.md). Every change runs under the same fetching rules: one request at a time, and never
around a CAPTCHA, a bot wall or a login.

- **▲ partial:** find a model it misses, add it as a test case in the adapter's YAML, record it with
  `manualbeagle adapters test <id> --record -v`, and widen the search (another step, a looser pattern, or a
  `strip_suffix` rule for the brand's market suffixes) until the case passes.
- **▲ link:** write the searching adapter. Open a product's support page with the browser's developer tools and
  find where the PDF links come from (the page's HTML, JSON embedded in it, or an API it calls), then add
  `search:` steps or a Python class and real test cases. Set `status: works` once they pass.
- **✗ blocked:** check whether the site still refuses automated requests. The adapter's header comment says what
  it answered and when; `curl -sI <a product support page>` shows whether it still answers 403 or a challenge
  page. If it has stopped, write a searching adapter as for ▲ link and drop the test cases' `skip`. If it still
  blocks, leave it blocked: you can still help by adding the maker's PDF hosts to `domains` (so web search ranks
  them first) and a `manual_page` a person can open.
- **✗ in Tested models:** the site changed. Run `manualbeagle adapters test <id> --live -v`, fix the adapter and
  re-record, or open a "Broken adapter" issue with that output.

## The brands

| Brand | Status | Tested models |{live_head} Notes |
|---|---|---|{live_rule}---|
"""

LIVE_NOTE = """

**Live:** the same cases against the real sites on {when}: passed out of run, with ✗ and the models that broke
(! is an error, such as a site that didn't answer)."""


def load_results(path: str | Path) -> list[dict]:
    """The case results `adapters test --json` wrote: a list of `CaseResult.as_dict()`."""
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _label(model: str, year: int | None) -> str:
    return f"{year} {model}" if year else model


def _code(text: object, limit: int = 200) -> str:
    """Text from a maker's site (a title, a URL, an error) as an inline code span, for a public issue.

    Inside a code span GitHub renders no mentions, links or images, so a page title such as "@someone" or
    "![x](...)" stays plain text. Backticks and line breaks are dropped so the span can't be closed early.
    """
    t = " ".join(str(text).replace("`", "'").split())[:limit]
    return f"`{t}`" if t else "–"


def live_cell(results: Iterable[dict]) -> str:
    """One adapter's live results as a table cell: "✓ 2/2", "✗ 1/2: FOO", or "–" when none ran."""
    ran = [r for r in results if r["status"] not in ("skip", "no-fixture")]
    if not ran:
        return "–"
    passed = sum(r["status"] == "pass" for r in ran)
    if passed == len(ran):
        return f"✓ {passed}/{len(ran)}"
    broken = ", ".join(
        f"{GLYPHS[r['status']]} {_label(r['model'], r.get('year'))}" for r in ran if r["status"] != "pass"
    )
    return f"✗ {passed}/{len(ran)}: {broken}"


def build(reg: Registry | None = None, live: list[dict] | None = None, live_when: str = "") -> str:
    """The text of docs/brands.md: the header, and a row per adapter from an offline run of its tests.

    Args:
        reg: the adapters (default: the built-in ones).
        live: results of a live run (`load_results()`); with them, the table gets a *Live* column.
        live_when: when that run was, for the header (default: today).
    """
    reg = reg or Registry()
    by_adapter: dict[str, list[dict]] = {}
    for r in live or []:
        by_adapter.setdefault(r["adapter"], []).append(r)
    rows = []
    for a in sorted(reg, key=lambda a: (list(STATUS).index(a.spec.status), a.brand.lower())):
        tested = []
        for case in a.spec.tests:
            r = run_case(a, case, mode="replay")
            g = {"pass": "✓", "skip": "–", "no-fixture": "?"}.get(r.status, "✗")
            tested.append(f"{g} {_label(case.model, case.year)}")
        notes = " ".join(a.spec.notes.split()).replace("|", "/")
        aliases = (
            f" (also {', '.join(a.spec.aliases[:4])}{'…' if len(a.spec.aliases) > 4 else ''})"
            if a.spec.aliases
            else ""
        )
        live_col = f" {live_cell(by_adapter.get(a.id, []))} |" if live is not None else ""
        rows.append(
            f"| **{a.brand}**{aliases} | {STATUS[a.spec.status]} | {', '.join(tested) or '—'} |{live_col} {notes} |"
        )
    head = HEADER.format(
        today=date.today().isoformat(),
        live_note=LIVE_NOTE.format(when=live_when or date.today().isoformat()) if live is not None else "",
        live_head=" Live |" if live is not None else "",
        live_rule="---|" if live is not None else "",
    )
    return head + "\n".join(rows) + "\n"


def breakage(results: list[dict], reg: Registry | None = None, run_url: str = "") -> tuple[str, int]:
    """A Markdown report of every case that broke in a live run, and how many broke.

    A case is broken when it failed, errored or was blocked (`testing.BROKEN`); skipped cases and passes are
    left out. The report groups cases by adapter, with the top results it found, so whoever picks it up can
    start from `manualbeagle adapters test <id> --live -v`. Everything that came from a site (titles, URLs,
    messages) is in code spans (`_code()`), since the report becomes a public GitHub issue.
    """
    reg = reg or Registry()
    broken = [r for r in results if r["status"] in BROKEN]
    ran = [r for r in results if r["status"] not in ("skip", "no-fixture")]
    when = date.today().isoformat()
    lines = [f"Live adapter run of {when}: **{len(ran) - len(broken)} of {len(ran)} cases passed**"]
    if run_url:
        lines[0] += f" ([the run]({run_url}))"
    lines[0] += "."
    if not broken:
        lines += ["", "✓ Every case that ran passed."]
        return "\n".join(lines) + "\n", 0
    lines += [
        "",
        "Each ✗ is a test case that no longer finds what its YAML expects on the maker's live site. A site that",
        "was down for one night passes again by itself; one that changed needs its adapter fixed and its fixtures",
        "re-recorded (CONTRIBUTING.md, *Tests*). Start with `manualbeagle adapters test <id> --live -v`.",
    ]
    by_adapter: dict[str, list[dict]] = {}
    for r in broken:
        by_adapter.setdefault(r["adapter"], []).append(r)
    for aid in sorted(by_adapter):
        try:
            a = reg.get(aid)
            title = f"{a.brand} (`{aid}`, {STATUS[a.spec.status]})"
        except KeyError:
            title = f"`{aid}`"
        lines += ["", f"### {title}", ""]
        for r in by_adapter[aid]:
            lines.append(
                f"- {GLYPHS[r['status']]} {r['status']}: {_code(_label(r['model'], r.get('year')))}: "
                f"{_code(r['message'])}"
            )
            for c in r.get("top", []):
                lines.append(
                    f"  - {c['score']:>3} {c['kind'] or '?'}: {_code(c['title'], 70)} {_code(c['url'])}"
                )
    return "\n".join(lines) + "\n", len(broken)
